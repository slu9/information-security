from datetime import datetime as ДатаВремя, timedelta as Интервал
from pathlib import Path as Путь
import sys as система

КОРЕНЬ = Путь(__file__).resolve().parents[1]
система.path.insert(0, str(КОРЕНЬ))
from данные.заявки_на_передачу import заявки_на_передачу
from программы.проверка_страны import проверить_страну


def рабочие_дни(начало, конец):
    день = начало
    количество = 0
    while день < конец:
        день += Интервал(days=1)
        if день.weekday() < 5:
            количество += 1
    return количество


def проверить_заявку(заявка):
    страна = проверить_страну(заявка["страна-получатель"])
    причины = []
    if страна["приговор"] == "запрещено":
        причины.append("Страна не прошла правовую оценку.")
    if not заявка["был ли уведомлён Роскомнадзор"]:
        причины.append("Роскомнадзор не уведомлён до начала передачи.")
    elif страна["число дней ожидания"]:
        дата = ДатаВремя.strptime(заявка["дата уведомления"], "%Y-%m-%d").date()
        сейчас = ДатаВремя.strptime(заявка["текущая дата"], "%Y-%m-%d").date()
        прошло = рабочие_дни(дата, сейчас)
        if прошло < 10:
            причины.append(f"После уведомления прошло только {прошло} из 10 рабочих дней.")

    особые = {"специальные", "биометрические"}
    if особые.intersection(заявка["виды передаваемых данных"]) and not заявка["есть ли согласие людей"]:
        причины.append("Для специальных или биометрических данных отсутствует отдельное письменное согласие.")

    return {
        "номер заявки": заявка["номер"],
        "страна": страна["название"],
        "итоговый приговор": "передача не разрешена" if причины else "передача разрешена",
        "причины": причины or ["Требования уведомления, ожидания и согласия соблюдены."],
        "условия страны": страна["список условий"],
    }


def обработать_все_заявки():
    результаты = [проверить_заявку(заявка) for заявка in заявки_на_передачу["заявки"]]
    путь = КОРЕНЬ / "отчёты" / "отчёт_по_передаче.txt"
    путь.parent.mkdir(exist_ok=True)
    строки = []
    for результат in результаты:
        строки.append(f"Заявка № {результат['номер заявки']}: {результат['итоговый приговор']}")
        строки.extend(f"- {причина}" for причина in результат["причины"])
        строки.append("")
    путь.write_text("\n".join(строки), encoding="utf-8")
    return результаты


if __name__ == "__main__":
    for итог in обработать_все_заявки():
        print(итог)
