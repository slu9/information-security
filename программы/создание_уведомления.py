from datetime import datetime as ДатаВремя
from pathlib import Path as Путь


def создать_уведомление(происшествие, путь_к_файлу):
    обязательные = {"дата и время обнаружения", "число пострадавших людей", "виды данных", "причина утечки", "принятые меры", "завершено внутреннее расследование"}
    if not обязательные.issubset(происшествие):
        raise ValueError("В сведениях о происшествии не хватает обязательных полей.")
    обнаружено = ДатаВремя.fromisoformat(происшествие["дата и время обнаружения"])
    сейчас = ДатаВремя.now()
    прошло_часов = (сейчас - обнаружено).total_seconds() / 3600
    if прошло_часов < 0:
        raise ValueError("Время обнаружения не может быть позже текущего времени.")
    дополнительное = происшествие["завершено внутреннее расследование"] or прошло_часов >= 24
    вид = "ДОПОЛНИТЕЛЬНОЕ" if дополнительное else "ПЕРВИЧНОЕ"
    срок = "72 часа" if дополнительное else "24 часа"
    расследование = "завершено; причиной признана: " + происшествие["причина утечки"] if происшествие["завершено внутреннее расследование"] else "продолжается; окончательные результаты ещё не установлены"
    просрочено = прошло_часов > (72 if дополнительное else 24)

    текст = f"""{вид} УВЕДОМЛЕНИЕ В РОСКОМНАДЗОР
об инциденте с персональными данными по ч. 3.1 ст. 21 Федерального закона № 152-ФЗ

Оператор: ООО «Северная Игра».
Дата и время обнаружения: {происшествие['дата и время обнаружения']}.
Текущая дата и время формирования: {сейчас.isoformat(timespec='minutes')}.
Число пострадавших субъектов: {происшествие['число пострадавших людей']}.
Виды данных: {', '.join(происшествие['виды данных'])}.
Предполагаемая причина: {происшествие['причина утечки']}.
Предполагаемый вред: риск мошенничества, раскрытия частной информации и неправомерного доступа к учётным записям.
Принятые меры: {происшествие['принятые меры']}.
Внутреннее расследование завершено: {'да' if происшествие['завершено внутреннее расследование'] else 'нет'}.
Результаты внутреннего расследования: {расследование}.
Сведения о лицах, действия которых стали причиной инцидента: не установлены.
Ответственное лицо для взаимодействия: Орлова Марина Сергеевна, privacy@severnaya-igra.example, +7 383 000-00-00.
Контрольный срок направления данного вида уведомления: {срок} с момента обнаружения.
Состояние срока: {'просрочен' if просрочено else 'не истёк'}.
"""
    путь = Путь(путь_к_файлу)
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(текст, encoding="utf-8")
    return {"вид уведомления": вид.lower(), "путь": str(путь), "прошло часов": round(прошло_часов, 1), "просрочено": просрочено}


if __name__ == "__main__":
    пример = {
        "дата и время обнаружения": ДатаВремя.now().isoformat(timespec="minutes"),
        "число пострадавших людей": 5000,
        "виды данных": ["электронная почта", "игровой идентификатор"],
        "причина утечки": "ошибка настройки доступа",
        "принятые меры": "доступ закрыт, ключи заменены",
        "завершено внутреннее расследование": False,
    }
    print(создать_уведомление(пример, Путь(__file__).resolve().parents[1] / "отчёты" / "уведомление.txt"))
