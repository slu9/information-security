def проверить_артефакты():
    поля_организации = {
        "название", "отрасль", "год основания", "годовая выручка в рублях",
        "количество сотрудников", "количество человек, чьи данные хранятся в базе",
        "список присутствующих видов данных", "признак наличия происшествий за 2024-2025 годы",
        "список отделений", "список стран для расширения деятельности",
        "фамилия, имя и отчество ответственного за обработку данных",
    }
    if set(организация) != поля_организации:
        raise ValueError("Паспорт организации имеет неверную структуру.")
    if организация["количество человек, чьи данные хранятся в базе"] != 300063:
        raise ValueError("В паспорте должно быть указано ровно 300 063 человека.")
    if any(set(отделение) != {"страна", "город", "число людей"} for отделение in организация["список отделений"]):
        raise ValueError("Неверная структура отделения организации.")
    if any(set(страна) != {"страна", "цель"} for страна in организация["список стран для расширения деятельности"]):
        raise ValueError("Неверная структура страны расширения.")

    записи = карта_данных.get("наборы данных", [])
    поля_карты = {"номер", "название набора данных", "вид данных", "откуда получены", "для чего обрабатываются", "правовое основание", "срок хранения в месяцах", "место хранения"}
    if len(записи) < 15:
        raise ValueError("Карта данных должна содержать не менее 15 записей.")
    виды = {"общедоступные", "специальные", "биометрические", "иные"}
    if any(set(запись) != поля_карты or запись["вид данных"] not in виды or "ст." not in запись["правовое основание"] for запись in записи):
        raise ValueError("Запись карты данных неполна или содержит недопустимые значения.")

    список_нарушений = нарушения.get("список нарушений", [])
    поля_нарушения = {"номер", "запись карты данных", "вид нарушения", "конкретная норма права с частью и пунктом", "текстовое описание сути нарушения", "размер штрафа в рублях", "правовое основание штрафа", "что нужно сделать для исправления"}
    if len(список_нарушений) != 3:
        raise ValueError("В файле нарушений должно быть ровно три нарушения.")
    номера = {запись["номер"] for запись in записи}
    if any(set(нарушение) != поля_нарушения or нарушение["запись карты данных"] not in номера for нарушение in список_нарушений):
        raise ValueError("Нарушение неполно или ссылается на отсутствующую запись карты.")

    поля_страны = {"название страны", "входит ли в перечень стран с достаточной защитой по версии Роскомнадзора", "входит ли в Конвенцию 108", "ссылка на источник", "краткое пояснение о правилах передачи"}
    if len(страны) < 20 or any(len(код) != 2 or set(сведения) != поля_страны for код, сведения in страны.items()):
        raise ValueError("Справочник должен содержать не менее 20 стран.")

    заявки = заявки_на_передачу.get("заявки", [])
    поля_заявки = {"номер", "страна-получатель", "виды передаваемых данных", "число людей", "цель передачи", "есть ли согласие людей", "был ли уведомлён Роскомнадзор", "дата уведомления", "текущая дата"}
    if len(заявки) != 3 or any(set(заявка) != поля_заявки for заявка in заявки):
        raise ValueError("Должно быть ровно три заявки на передачу.")

    обязательные = {"согласие_сотрудника.txt", "согласие_клиента.txt", "политика.txt", "уведомление_об_утечке.txt"}
    папка = КОРЕНЬ / "данные" / "документы"
    найденные = {путь.name for путь in папка.glob("*.txt")}
    if not обязательные.issubset(найденные):
        raise ValueError("Не хватает обязательных текстовых документов.")
    if len((папка / "политика.txt").read_text(encoding="utf-8").split()) < 1500:
        raise ValueError("Политика должна содержать не менее 1500 слов.")


def проверить_документы():
    результаты = {}
    for путь in sorted((КОРЕНЬ / "данные" / "документы").glob("*.txt")):
        if путь.name == "согласие_сотрудника.txt":
            вид = "работник"
        elif путь.name == "согласие_клиента.txt":
            вид = "клиент"
        else:
            вид = "иной документ"
        итог = проверить_согласие(путь.read_text(encoding="utf-8"), вид)
        число_ошибок = len(итог["каких обязательных частей не хватает"])
        итог["состояние"] = "в порядке" if итог["правильный ли документ"] else ("замечание" if число_ошибок <= 2 else "грубая ошибка")
        результаты[путь.name] = итог
    return результаты


def пересчитать_нарушения():
    результаты = []
    выручка = организация["годовая выручка в рублях"]
    люди = организация["количество человек, чьи данные хранятся в базе"]
    for нарушение in нарушения["список нарушений"]:
        расчёт = рассчитать_штраф(нарушение["вид нарушения"], люди, False, выручка)
        результаты.append({"нарушение": нарушение, "расчёт": расчёт})
    return результаты


def разобрать_запрос(текст):
    нижний = текст.lower().replace("ё", "е")
    действие = "передача" if any(слово in нижний for слово in ["передать", "передача", "отправить"]) else ("происшествие" if any(слово in нижний for слово in ["утечка", "утекли", "взлом", "инцидент"]) else "не определено")
    повторность = any(слово in нижний for слово in ["повторн", "снова", "второй раз"])

    совпадение = образцы.search(r"\b\d[\d\s]*\b", нижний)
    число = int(образцы.sub(r"\s", "", совпадение.group())) if совпадение else 0

    код = None
    for код_страны, сведения in страны.items():
        варианты = {сведения["название страны"].lower().replace("ё", "е")}
        if код_страны == "US":
            варианты.update({"сша", "америк"})
        if код_страны == "CN":
            варианты.update({"китай", "кнр"})
        if код_страны == "GB":
            варианты.update({"великобритани", "англи"})
        if any(вариант in нижний for вариант in варианты):
            код = код_страны
            break

    if "биометр" in нижний or "голос" in нижний or "изображение лица" in нижний:
        вид_данных = "биометрические"
    elif "здоров" in нижний or "медицин" in нижний:
        вид_данных = "специальные"
    else:
        вид_данных = "иные"

    результат = {"исходный текст": текст, "действие": действие, "число людей": число, "вид данных": вид_данных, "код страны": код, "повторность": повторность}
    if код:
        результат["проверка страны"] = проверить_страну(код)
    if действие == "происшествие":
        размер = "малого" if число < 10000 else ("среднего" if число <= 100000 else "крупного")
        вид_штрафа = "нарушение по биометрии" if вид_данных == "биометрические" else ("утечка специальной категории" if вид_данных == "специальные" else f"утечка {размер} размера")
        результат["оценка штрафа"] = рассчитать_штраф(вид_штрафа, число, повторность, организация["годовая выручка в рублях"])
    return результат


def сформировать_отчёт(документы, оценки_нарушений, разбор, имя_файла="итоговый_отчёт.txt"):
    строки = [
        "ИТОГОВЫЙ ОТЧЁТ О СООТВЕТСТВИИ",
        "",
        "1. Общие сведения об организации",
        f"Название: {организация['название']}",
        f"Отрасль: {организация['отрасль']}",
        f"Год основания: {организация['год основания']}",
        f"Годовая выручка: {организация['годовая выручка в рублях']:,} руб.",
        f"Сотрудников: {организация['количество сотрудников']}",
        f"Людей в базе: {организация['количество человек, чьи данные хранятся в базе']:,}",
        f"Ответственный: {организация['фамилия, имя и отчество ответственного за обработку данных']}",
        "",
        "2. Итоги проверки документов",
    ]
    риск = 0
    штрафные_баллы = 0
    for имя, итог in документы.items():
        строки.append(f"{имя}: {итог['состояние']}; {итог['текстовое пояснение']} Штраф: {итог['размер возможного штрафа в рублях']} руб.")
        риск += итог["размер возможного штрафа в рублях"]
        штрафные_баллы += 10 if итог["состояние"] == "замечание" else (20 if итог["состояние"] == "грубая ошибка" else 0)

    строки.extend(["", "3. Найденные нарушения"])
    for элемент in оценки_нарушений:
        нарушение = элемент["нарушение"]
        расчёт = элемент["расчёт"]
        максимум = расчёт["наибольший размер штрафа"]
        риск += максимум
        штрафные_баллы += 15
        строки.extend([
            f"Нарушение № {нарушение['номер']}, запись карты № {нарушение['запись карты данных']}: {нарушение['текстовое описание сути нарушения']}",
            f"Норма: {нарушение['конкретная норма права с частью и пунктом']}",
            f"Оценка штрафа: {расчёт['наименьший размер штрафа в рублях']:,}–{максимум:,} руб.",
            f"Исправление: {нарушение['что нужно сделать для исправления']}",
        ])

    строки.extend(["", "4. Разбор запроса пользователя", f"Запрос: {разбор['исходный текст']}", f"Действие: {разбор['действие']}", f"Число людей: {разбор['число людей']}", f"Вид данных: {разбор['вид данных']}", f"Повторность: {'да' if разбор['повторность'] else 'нет'}"])
    if разбор.get("проверка страны"):
        страна = разбор["проверка страны"]
        строки.extend([
            f"Страна: {страна['название']} ({страна['код']})",
            f"Приговор: {страна['приговор']}",
            "Условия: " + "; ".join(страна["список условий"]),
            "Ссылки на закон: " + "; ".join(страна["список ссылок на закон"]),
        ])
    else:
        строки.append("Страна: не указана или не распознана.")
    if разбор.get("оценка штрафа"):
        оценка = разбор["оценка штрафа"]
        строки.append(f"Штраф по ситуации: {оценка['наименьший размер штрафа в рублях']:,}–{оценка['наибольший размер штрафа']:,} руб.")
        строки.append(f"Оборотный штраф: {'да' if оценка['применим ли оборотный штраф'] else 'нет'}.")
        строки.append("Обоснование: " + оценка["правовое обоснование расчёта"])
        риск += оценка["наибольший размер штрафа"]
        штрафные_баллы += 10

    оценка_соответствия = max(0, 100 - штрафные_баллы)
    строки.extend([
        "",
        "5. Итоговая оценка",
        f"Оценка соответствия: {оценка_соответствия} из 100.",
        f"Общий риск штрафов: до {риск:,} руб.",
        "Первоочередные действия:",
        "1. Остановить незаконную обработку голосовой биометрии и удалить неправомерно собранные слепки.",
        "2. Уточнить уведомление оператора в Роскомнадзоре по внешним тестировщикам.",
        "3. Прекратить передачу телеметрии в США до отдельного согласия, уведомления и истечения 10 рабочих дней.",
        "4. Провести повторную проверку карты данных и подтвердить выполненные исправления актами.",
    ])
    путь = КОРЕНЬ / "отчёты" / Путь(имя_файла).name
    путь.parent.mkdir(exist_ok=True)
    путь.write_text("\n".join(строки), encoding="utf-8")
    return путь, оценка_соответствия, риск


def главный_цикл():
    try:
        проверить_артефакты()
    except (ValueError, KeyError, TypeError) as ошибка:
        print(f"Ошибка структуры проекта: {ошибка}")
        return

    документы = проверить_документы()
    оценки = пересчитать_нарушения()
    print("Симулятор ООО «Северная Игра». Опишите ситуацию или введите «выход».")
    while True:
        запрос = input("> ").strip()
        if запрос.lower() in {"выход", "quit", "exit"}:
            print("Работа завершена.")
            break
        разбор = разобрать_запрос(запрос)
        путь, оценка, риск = сформировать_отчёт(документы, оценки, разбор)
        print(f"Действие: {разбор['действие']}; людей: {разбор['число людей']}; вид данных: {разбор['вид данных']}.")
        if разбор.get("проверка страны"):
            print(f"Страна: {разбор['проверка страны']['название']}; приговор: {разбор['проверка страны']['приговор']}.")
        print(f"Оценка соответствия: {оценка}/100. Риск штрафов: до {риск:,} руб.")
        print(f"Отчёт обновлён: {путь}")


if __name__ == "__main__":
    главный_цикл()
