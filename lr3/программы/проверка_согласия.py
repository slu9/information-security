from pathlib import Path as Путь

КОРЕНЬ = Путь(__file__).resolve().parents[1]


def проверить_согласие(текст, вид_документа):
    вид = вид_документа.lower()
    if вид not in {"работник", "клиент"}:
        return {"правильный ли документ": True, "каких обязательных частей не хватает": [], "размер возможного штрафа в рублях": 0, "текстовое пояснение": "Документ не является согласием; специальная проверка не применяется."}

    нижний = текст.lower()
    нехватка = []
    ссылки_на_основной_документ = ["договор", "оферт", "основн" + "ого документа", "основн" + "ом документе"]
    if any(признак in нижний for признак in ссылки_на_основной_документ):
        нехватка.append("согласие должно быть отдельным документом")

    проверки = {
        "конкретные цели обработки": ["цель обработки", "целями обработки"],
        "конкретный перечень данных": ["перечень персональных данных", "обрабатываются следующие"],
        "срок действия согласия": ["срок действия", "действует до"],
        "порядок отзыва": ["отозвать", "отзыв согласия"],
    }
    for часть, признаки in проверки.items():
        if not any(признак in нижний for признак in признаки):
            нехватка.append(часть)

    штраф = min(700000, 100000 + 150000 * len(нехватка)) if нехватка else 0
    правильно = not нехватка
    пояснение = "Согласие соответствует заданным правилам проверки." if правильно else "Согласие не соответствует ч. 1 ст. 9 Федерального закона № 152-ФЗ: " + "; ".join(нехватка) + "."
    return {
        "правильный ли документ": правильно,
        "каких обязательных частей не хватает": нехватка,
        "размер возможного штрафа в рублях": штраф,
        "текстовое пояснение": пояснение,
    }


def обработать_согласия():
    папка = КОРЕНЬ / "данные" / "документы"
    результаты = {}
    for путь in sorted(папка.glob("согласие_*.txt")):
        вид = "работник" if "сотрудника" in путь.name else "клиент"
        результаты[путь.name] = проверить_согласие(путь.read_text(encoding="utf-8"), вид)

    отчёт = КОРЕНЬ / "отчёты" / "отчёт_по_согласиям.txt"
    отчёт.parent.mkdir(exist_ok=True)
    строки = []
    for имя, итог in результаты.items():
        строки.append(f"{имя}: {'правильный' if итог['правильный ли документ'] else 'неправильный'}")
        строки.append(итог["текстовое пояснение"])
        строки.append(f"Возможный штраф: {итог['размер возможного штрафа в рублях']} руб.\n")
    отчёт.write_text("\n".join(строки), encoding="utf-8")
    return результаты


if __name__ == "__main__":
    for документ, результат in обработать_согласия().items():
        print(документ, результат)
