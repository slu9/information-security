from данные.страны import страны


def проверить_страну(код_страны):
    код = код_страны.strip().upper()
    сведения = страны.get(код)
    if not сведения:
        return {
            "код": код,
            "название": "неизвестная страна",
            "приговор": "запрещено",
            "список условий": ["Добавить страну в справочник и провести правовую оценку."],
            "список ссылок на закон": ["ст. 12 Федерального закона № 152-ФЗ"],
            "число дней ожидания": 10,
        }

    if код == "RU":
        приговор = "разрешено"
        условия = ["Соблюдать локализацию баз данных граждан РФ."]
        ожидание = 0
    elif сведения["входит ли в перечень стран с достаточной защитой по версии Роскомнадзора"]:
        приговор = "разрешено при условиях"
        условия = [
            "До начала передачи оценить меры защиты иностранного получателя.",
            "Направить отдельное уведомление в Роскомнадзор.",
            "Не передавать данные при получении решения о запрете или ограничении.",
        ]
        ожидание = 0
    else:
        приговор = "разрешено при условиях"
        условия = [
            "Получить сведения о защите и праве страны получателя.",
            "Направить отдельное уведомление в Роскомнадзор.",
            "Выждать 10 рабочих дней и проверить отсутствие запрета.",
        ]
        ожидание = 10

    return {
        "код": код,
        "название": сведения["название страны"],
        "приговор": приговор,
        "список условий": условия,
        "список ссылок на закон": [
            "ч. 3–5, 7–12 ст. 12 Федерального закона № 152-ФЗ",
            сведения["ссылка на источник"],
        ],
        "число дней ожидания": ожидание,
    }


if __name__ == "__main__":
    print(проверить_страну(input("Введите код страны: ")))
